manifest = json.loads((ROOT/'by-type-manifest.json').read_text())
by_file = collections.defaultdict(collections.Counter)
messages = collections.defaultdict(collections.Counter)
first = {}


def group_of(rule, message):
    match = re.search(r'Leader/(\d+(?:-\d+)?)', message)
    return rule + ('-Leader-'+match[1] if rule == 'LD-02' and match else '')


for path in sorted(ROOT.glob('*.diagnostic.summary.json')):
    summary = json.loads(path.read_text())
    for entry in summary['messages'].values():
        error = entry['first']
        group = group_of(error['rule'], error['message'])
        by_file[group][summary['file']] += entry['count']
        messages[group][error['message']] += entry['count']
        first.setdefault((group,error['message']), (summary['file'],error))
for group, chunks in manifest['chunks'].items():
    if not group.startswith('PARSE-'): continue
    for chunk in chunks:
        with gzip.open(chunk,'rt',encoding='utf8',newline='') as source:
            for row in csv.DictReader(source,delimiter='\t'):
                by_file[group][row['file']] += 1
                messages[group][row['message']] += 1
                first.setdefault((group,row['message']), (row['file'],{'byteOffset':int(row['byteOffset']), 'recordIndex':int(row['recordIndex']), 'message':row['message']}))

