/** Regenerate the offline documentation examples from the actual converter. */
import { readFileSync, writeFileSync } from "node:fs";
import { Iso2709MarcParser } from "../src/marc-parser.js";
import { MarcJsonSerializer } from "../src/marc-json-serializer.js";
import { MarcIsoSerializer } from "../src/marc-iso-serializer.js";
const parser = new Iso2709MarcParser();
const json = new MarcJsonSerializer("utf-8");
const iso = new MarcIsoSerializer("utf-8");
const demo = iso.serialize({leader: "00000nam a2200000   4500", format: "BK", fields: [
  {code: "001", value: "000000001"},
  {code: "008", value: "260930s2026^^^^ru^^^^^^^^^^^^^^^^^^rus^^"},
  {code: "245", ind1: "1", ind2: "0", subfields: [{code: "a", value: "Пример книги"}, {code: "b", value: "MARC → JSON"}]},
]});
const samples = [
  {name: "Учебная запись", bytes: demo},
  {name: "Реальная запись · 015316815", bytes: readFileSync("docs/015316815/015316815.mrc")},
].map(({name, bytes}) => {
  const record = parser.parseForImport(bytes)!;
  const output = json.serialize(record);
  const rebuilt = iso.serialize(output);
  return {name, bytes: [...bytes], output, rebuilt: [...rebuilt], fields: record.directory.map((entry, i) => ({
    tag: entry.tag, start: Number(record.leader.baseAddressOfData) + Number(entry.startingCharacterPosition),
    length: Number(entry.fieldLength), directoryStart: 24 + i * 12,
  }))};
});
writeFileSync("docs/marc-explorer/examples.js", `// Generated by scripts/build-marc-explorer.ts; do not edit.\nconst examples = ${JSON.stringify(samples)};\n`);
